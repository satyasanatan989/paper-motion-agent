"""HyperFrames Project Bridge for PaperMotion.

Exports a PaperMotion StoryboardPlan into a fully compliant HyperFrames project
structure, adhering to the HeyGen HyperFrames contract:
  1. index.html: Root composition declaring variables, tracks, audio, and sub-composition mounts.
  2. compositions/scene_XXX.html: Self-contained scene sub-compositions wrapped in <template>,
     styled via #root, registering deterministic timelines on window.__timelines.
  3. assets/: Relative asset bindings.
  4. Compatibility: Direct support for `npx hyperframes check`, `preview`, and `render`.
"""

from __future__ import annotations

import html
import json
from pathlib import Path
from typing import List, Optional

from storyboard.generator import StoryboardPlan, ScenePlan
from visual_engine.hyperframes_primitives import HyperFramesPrimitives


class HyperFramesBridge:
    """Bridges PaperMotion storyboard generation with the HyperFrames video framework."""

    def __init__(self, output_root: Optional[Path] = None):
        self.output_root = Path(output_root) if output_root else Path("./hyperframes_export")

    def export_project(self, storyboard: StoryboardPlan, project_dir: Optional[Path] = None) -> Path:
        """Exports a complete HyperFrames project directory from a StoryboardPlan."""
        target_dir = Path(project_dir) if project_dir else self.output_root / storyboard.project_name
        target_dir.mkdir(parents=True, exist_ok=True)

        compositions_dir = target_dir / "compositions"
        assets_dir = target_dir / "assets"
        compositions_dir.mkdir(parents=True, exist_ok=True)
        assets_dir.mkdir(parents=True, exist_ok=True)

        # 1. Export scene sub-compositions
        scene_hosts_html: List[str] = []
        current_time_offset = 0.0

        for idx, scene in enumerate(storyboard.scenes):
            scene_cid = f"scene_{idx + 1:03d}"
            sub_comp_path = compositions_dir / f"{scene_cid}.html"
            sub_comp_content = self._generate_scene_subcomposition(scene, scene_cid, storyboard.fps)
            with open(sub_comp_path, "w", encoding="utf-8") as f:
                f.write(sub_comp_content)

            # Build root mount clip
            scene_duration = scene.duration
            scene_hosts_html.append(
                f"""    <!-- Scene {idx + 1}: {html.escape(scene.title)} -->
    <div
      id="{scene_cid}-host"
      class="clip"
      data-start="{current_time_offset:.2f}"
      data-duration="{scene_duration:.2f}"
      data-track-index="{idx}"
      data-composition-id="{scene_cid}"
      data-composition-src="compositions/{scene_cid}.html"
      data-track-kind="graphics"
    ></div>"""
            )
            current_time_offset += scene_duration

        total_duration = max(storyboard.estimated_duration, current_time_offset)

        # 2. Export root index.html
        root_html = self._generate_root_index_html(storyboard, total_duration, scene_hosts_html)
        root_path = target_dir / "index.html"
        with open(root_path, "w", encoding="utf-8") as f:
            f.write(root_html)

        # 3. Export project manifest / metadata
        manifest = {
            "name": storyboard.project_name,
            "topic": storyboard.topic,
            "duration": total_duration,
            "fps": storyboard.fps,
            "aspect_ratio": storyboard.aspect_ratio,
            "width": storyboard.resolution.get("width", 1080),
            "height": storyboard.resolution.get("height", 1920),
            "scenes_count": len(storyboard.scenes),
            "framework": "hyperframes-heygen",
            "hyperframes_cli_ready": True
        }
        with open(target_dir / "hyperframes.json", "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2)

        return target_dir

    def _generate_root_index_html(
        self,
        storyboard: StoryboardPlan,
        total_duration: float,
        scene_hosts: List[str]
    ) -> str:
        """Generates the root index.html composition following HyperFrames contract."""
        w = storyboard.resolution.get("width", 1080)
        h = storyboard.resolution.get("height", 1920)

        variables = [
            {"id": "topic", "type": "string", "role": "content", "default": storyboard.topic},
            {"id": "author", "type": "string", "role": "content", "default": "PaperMotion AI"},
            {"id": "accent", "type": "color", "role": "style", "default": "#F46A38"}
        ]
        var_json = html.escape(json.dumps(variables))

        joined_hosts = "\n".join(scene_hosts)

        return f"""<!doctype html>
<!--
  HyperFrames Root Composition - Generated by PaperMotion Agent
  Contract:
    - Root duration defines video length
    - Sub-compositions mounted from compositions/
    - Deterministic timeline seek via window.__timelines
-->
<html
  lang="en"
  data-composition-id="root"
  data-composition-duration="{total_duration:.2f}"
  data-composition-variables='{var_json}'
>
<head>
  <meta charset="UTF-8">
  <title>{html.escape(storyboard.topic)} - HyperFrames</title>
  <style>
    *, *::before, *::after {{
      box-sizing: border-box;
    }}
    html, body {{
      margin: 0;
      padding: 0;
      width: 100%;
      height: 100%;
      background: #111318;
      overflow: hidden;
      font-family: 'Inter', -apple-system, sans-serif;
    }}
    #root {{
      position: absolute;
      inset: 0;
      width: {w}px;
      height: {h}px;
      overflow: hidden;
      container-type: size;
    }}
    .clip {{
      position: absolute;
      inset: 0;
      overflow: hidden;
    }}
    /* Global Papercraft Rig Overlay */
    .global-rig-overlay {{
      position: absolute;
      inset: 0;
      pointer-events: none;
      z-index: 999;
      box-shadow: inset 0 0 100px rgba(0, 0, 0, 0.45);
    }}
  </style>
</head>
<body>
  <div
    id="root"
    class="clip"
    data-start="0"
    data-duration="{total_duration:.2f}"
    data-track-index="0"
  >
{joined_hosts}
    <div class="global-rig-overlay"></div>
  </div>
</body>
</html>
"""

    def _generate_scene_subcomposition(
        self,
        scene: ScenePlan,
        composition_id: str,
        fps: int = 30
    ) -> str:
        """Generates a self-contained sub-composition adhering to the HyperFrames template contract."""
        dur = scene.duration
        escaped_id = html.escape(composition_id)
        escaped_title = html.escape(scene.title)
        headline_sub = html.escape(scene.typography.headline_sub or "")
        headline_main = html.escape(scene.typography.headline_main or scene.title)

        # Handle annotation
        annotation_markup = ""
        anno_data = getattr(scene, "annotation", None)
        if isinstance(anno_data, dict):
            kw = anno_data.get("keyword", scene.keywords[0] if scene.keywords else "FOCUS")
            nt = anno_data.get("note", "CRITICAL FACTOR")
            st = anno_data.get("style", "highlight")
            ac = anno_data.get("accent", "burnt_orange")
            annotation_markup = HyperFramesPrimitives.render_vox_annotate_markup(
                keyword=kw,
                note=nt,
                style=st,
                accent=ac,
                widget_id=f"{composition_id}-anno"
            )
        elif scene.keywords:
            # Fallback Vox annotation for first keyword
            annotation_markup = HyperFramesPrimitives.render_vox_annotate_markup(
                keyword=scene.keywords[0],
                note="KEY MARKER",
                style="highlight",
                accent="burnt_orange",
                widget_id=f"{composition_id}-anno"
            )

        # HyperFrames CSS rules
        hf_css = HyperFramesPrimitives.get_hyperframes_css_rules()

        return f"""<!doctype html>
<!--
  HyperFrames Scene Sub-composition: {escaped_id}
  Title: {escaped_title}
  Template mount: The runtime clones only the <template> element.
-->
<html
  lang="en"
  data-composition-id="{escaped_id}"
  data-composition-duration="{dur:.2f}"
>
<head>
  <meta charset="UTF-8">
  <title>{escaped_title}</title>
</head>
<body>
  <template>
    <div id="root" data-composition-id="{escaped_id}" data-duration="{dur:.2f}" data-fps="{fps}">
      <style>
        *, *::before, *::after {{
          box-sizing: border-box;
        }}
        #root {{
          position: absolute;
          inset: 0;
          overflow: hidden;
          container-type: size;
          background: #F4EFE6;
          color: #1A140E;
          font-family: 'Inter', system-ui, sans-serif;
        }}
        .scene-container {{
          position: absolute;
          inset: 0;
          padding: 80px 48px;
          display: flex;
          flex-direction: column;
          justify-content: flex-start;
          align-items: flex-start;
        }}
        .typo-rig {{
          margin-top: 40px;
          will-change: transform, opacity;
        }}
        .headline-sub {{
          font-family: 'Bebas Neue', sans-serif;
          font-size: 32px;
          color: #8C6D37;
          letter-spacing: 0.1em;
          text-transform: uppercase;
          margin-bottom: 4px;
        }}
        .headline-main {{
          font-family: 'Impact', sans-serif;
          font-size: 64px;
          color: #F46A38;
          letter-spacing: 0.02em;
          text-transform: uppercase;
          line-height: 1.05;
          text-shadow: 2px 4px 8px rgba(0,0,0,0.25);
        }}
        .stage-center {{
          position: relative;
          width: 100%;
          flex: 1;
          display: grid;
          place-items: center;
        }}
{hf_css}
      </style>

      <div class="scene-container">
        <div class="typo-rig" id="{escaped_id}-typo">
          <div class="headline-sub">{headline_sub}</div>
          <div class="headline-main">{headline_main}</div>
        </div>

        <div class="stage-center">
          {annotation_markup}
        </div>
      </div>

      <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
      <script>
        (function () {{
          "use strict";
          var compositionId = "{escaped_id}";
          var root = document.querySelector('[data-composition-id="' + compositionId + '"]');
          var tl = gsap.timeline({{ paused: true }});

          // Entrance
          tl.from("#{escaped_id}-typo", {{
            y: 40,
            opacity: 0,
            duration: 0.6,
            ease: "power3.out"
          }}, 0.1);

          // Vox annotation trigger
          var annoEl = root ? root.querySelector(".vox-annotate-container") : null;
          if (annoEl) {{
            tl.call(function() {{
              annoEl.classList.add("active");
            }}, null, 0.7);
          }}

          // Register with HyperFrames deterministic timeline seek registry
          window.__timelines = window.__timelines || {{}};
          window.__timelines["{escaped_id}"] = tl;
        }})();
      </script>
    </div>
  </template>
</body>
</html>
"""
